function commonsURL(filename) {
  return (
    "https://commons.wikimedia.org/wiki/Special:FilePath/" +
    encodeURIComponent(filename) +
    "?width=1100"
  );
}

function commonsPage(filename) {
  return (
    "https://commons.wikimedia.org/wiki/File:" +
    encodeURIComponent(filename)
  );
}

function photo(key, caption) {
  const file = photoFiles[key];

  if (!file) return "";

  return `
    <figure class="picture">

      <img
        src="${commonsURL(file)}"
        alt="${caption}"
        loading="lazy"
        onerror="
          this.style.display='none';
          this.nextElementSibling.style.display='block';
        "
      >

      <div class="image-error">
        Сурет жүктелмеді.
        Суретті дереккөзден ашуға болады.
      </div>

      <figcaption>
        ${caption}.
        Дереккөз:
        <a href="${commonsPage(file)}"
           target="_blank"
           rel="noopener noreferrer">
          Wikimedia Commons
        </a>
      </figcaption>

    </figure>
  `;
}

