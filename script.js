const STORAGE_KEY = "darkhan-handcraft-34-scores";

let awarded = [{}, {}, {}];

try {
  const saved = JSON.parse(
    localStorage.getItem(STORAGE_KEY)
  );

  if (
    Array.isArray(saved) &&
    saved.length === 3 &&
    saved.every(
      item => item &&
      typeof item === "object" &&
      !Array.isArray(item)
    )
  ) {
    awarded = saved;
  }
} catch (error) {
  awarded = [{}, {}, {}];
}

function saveScores() {
  try {
    localStorage.setItem(
      STORAGE_KEY,
      JSON.stringify(awarded)
    );
  } catch (error) {
    // Сақтау қолжетімсіз болса да,
    // сабақ жұмысын жалғастыра береді.
  }
}

function teamScore(index) {
  return Object.values(awarded[index]).reduce(
    (sum, value) =>
      sum + (Number.isFinite(value) ? value : 0),
    0
  );
}

function updateScoreboard() {
  document.getElementById("scoreboard").innerHTML =
    awarded.map((_, index) => `
      <div class="score-row">
        <span>${index + 1}-команда</span>
        <strong>${teamScore(index)} ұпай</strong>
      </div>
    `).join("");

  if (currentStage === 7) {
    renderFinalScores();
  }
}

function awardButton(team, key, points) {
  const active = Boolean(awarded[team][key]);

  return `
    <button
      class="award ${active ? "active" : ""}"
      data-award="${team}|${key}|${points}"
    >
      ${active ? "✓ Ұпай берілді" : "+" + points + " ұпай"}
    </button>
  `;
}

function refreshAwardButtons() {
  document.querySelectorAll("[data-award]")
    .forEach(button => {
      const [team, key, points] =
        button.dataset.award.split("|");

      const active = Boolean(
        awarded[Number(team)][key]
      );

      button.textContent = active
        ? "✓ Ұпай берілді"
        : "+" + points + " ұпай";

      button.classList.toggle("active", active);
    });
}

function toggleAward(team, key, points) {
  if (!awarded[team]) return;

  if (awarded[team][key]) {
    delete awarded[team][key];
  } else {
    awarded[team][key] = points;
  }

  saveScores();
  refreshAwardButtons();
  updateScoreboard();
}

