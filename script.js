document.addEventListener("click", function(event) {

  // Кезеңді ауыстыру
  const stageButton =
    event.target.closest("[data-stage]");

  if (stageButton) {
    showPage(Number(stageButton.dataset.stage));
    return;
  }

  // Жауапты ашу немесе жасыру
  const revealButton =
    event.target.closest("[data-reveal]");

  if (revealButton) {
    const id = revealButton.dataset.reveal;

    const answer = document.getElementById(id);

    if (!answer) return;

    answer.classList.toggle("visible");

    revealButton.textContent =
      answer.classList.contains("visible")
        ? "Жауапты жасыру"
        : "Жауабын көрсету";

    return;
  }

  // Команда ұпайы
  const awardControl =
    event.target.closest("[data-award]");

  if (awardControl) {
    const [team, key, points] =
      awardControl.dataset.award.split("|");

    toggleAward(
      Number(team),
      key,
      Number(points)
    );

    return;
  }

  // Студент таңдау
  if (event.target.closest("#pickStudent")) {
    pickStudent();
    return;
  }
});

