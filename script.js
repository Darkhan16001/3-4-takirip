function renderNavigation() {
  document.getElementById("stageNav").innerHTML =
    stages.map((stage, index) => `
      <button
        class="stage-button ${
          index === currentStage ? "active" : ""
        }"
        data-stage="${index}"
      >
        <span>
          ${index + 1}. ${stage.name}
        </span>

        <small>
          ${stage.minutes} мин
        </small>
      </button>
    `).join("");
}

function showPage(index) {
  if (index < 0 || index >= pages.length) {
    return;
  }

  currentStage = index;

  document.getElementById("content").innerHTML =
    pages[index]();

  document.getElementById("stageTitle").textContent =
    stages[index].name;

  document.getElementById("pageCount").textContent =
    `${index + 1} / ${pages.length}`;

  document.getElementById("progressBar").style.width =
    ((index + 1) / pages.length * 100) + "%";

  document.getElementById("previous").disabled =
    index === 0;

  document.getElementById("next").disabled =
    index === pages.length - 1;

  document.getElementById("next").textContent =
    index === pages.length - 2
      ? "Қорытындыға өту →"
      : "Келесі бет →";

  renderNavigation();

  if (index === 5) {
    const input = document.getElementById("studentNames");

    if (input) {
      input.value = studentNamesText;
    }
  }

  if (index === 6) {
    refreshAwardButtons();
  }

  if (index === 7) {
    renderFinalScores();
  }

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });
}

