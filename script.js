function pickStudent() {
  const input = document.getElementById("studentNames");

  if (!input) return;

  const names = input.value.trim();

  if (!names) {
    document.getElementById("studentResult")
      .textContent = "Алдымен есімдерді енгізіңдер.";
    return;
  }

  if (names !== studentNamesText) {
    studentNamesText = names;

    availableStudents = names
      .split(/[,;\n]+/)
      .map(name => name.trim())
      .filter(Boolean);
  }

  if (availableStudents.length === 0) {
    availableStudents = studentNamesText
      .split(/[,;\n]+/)
      .map(name => name.trim())
      .filter(Boolean);
  }

  const randomIndex = Math.floor(
    Math.random() * availableStudents.length
  );

  const selected =
    availableStudents.splice(randomIndex, 1)[0];

  document.getElementById("studentResult")
    .textContent =
    "Таңдалған студент: " + selected;
}

